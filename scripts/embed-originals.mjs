// Embeds dam-originals/*.jpg into lib/originals.mjs so the fake DAM function
// needs no filesystem access at runtime. Re-run after changing the images.
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";

const dir = new URL("../dam-originals/", import.meta.url);
const files = (await readdir(dir)).filter((f) => f.endsWith(".jpg")).sort();

let out = "// Generated by scripts/embed-originals.mjs. Do not edit.\nexport const ORIGINALS = {\n";
for (const file of files) {
  const bytes = await readFile(new URL(file, dir));
  const etag = `"${createHash("sha256").update(bytes).digest("hex").slice(0, 16)}"`;
  out += `  ${JSON.stringify(file)}: { etag: ${JSON.stringify(etag)}, base64: ${JSON.stringify(bytes.toString("base64"))} },\n`;
}
out += "};\n";

await writeFile(new URL("../lib/originals.mjs", import.meta.url), out);
console.log(`embedded ${files.length} images`);
